/**
 * Pins the SPDX license list and the legal texts the catalog hashes.
 *
 *   bun scripts/pin-legal-texts.ts              fetch the list and texts at SPDX_TAG, then hash
 *   bun scripts/pin-legal-texts.ts --hash-only  rehash legal/*.txt without fetching
 *
 * Fetching writes src/spdx/list.generated.ts and legal/<id>.txt byte for byte. Hashing writes
 * legal/hashes.generated.json with the SHA-256 of every legal/*.txt. Run by hand; commit the output.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { sha256 } from '@noble/hashes/sha2'
import { bytesToHex } from '@noble/hashes/utils'

const SPDX_TAG = 'v3.29.0'
const SPDX_VERSION = SPDX_TAG.slice(1)
const BASE = `https://raw.githubusercontent.com/spdx/license-list-data/${SPDX_TAG}/`
/** Licenses whose text the catalog pins. */
const TEXT_IDS = [
  'CC0-1.0',
  'CC-BY-4.0',
  'CC-BY-SA-4.0',
  'CC-BY-NC-4.0',
  'CC-BY-NC-SA-4.0',
  'CC-BY-ND-4.0',
  'CC-BY-NC-ND-4.0',
]

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const legalDir = join(root, 'legal')

async function get(path: string): Promise<Response> {
  const response = await fetch(BASE + path)
  if (!response.ok) throw new Error(`GET ${BASE + path}: ${response.status}`)
  return response
}

async function fetchAll(): Promise<void> {
  let licenses: Response
  try {
    licenses = await get('json/licenses.json')
  } catch (error) {
    console.error(`SPDX license-list-data tag ${SPDX_TAG} not found: ${(error as Error).message}`)
    process.exit(1)
  }
  const list = (await licenses.json()) as {
    licenseListVersion: string
    licenses: { licenseId: string; isDeprecatedLicenseId: boolean }[]
  }
  if (list.licenseListVersion !== SPDX_VERSION) {
    throw new Error(`licenses.json says version ${list.licenseListVersion}, expected ${SPDX_VERSION}`)
  }
  const exceptions = (await (await get('json/exceptions.json')).json()) as {
    exceptions: { licenseExceptionId: string }[]
  }

  const ids = list.licenses.map((l) => l.licenseId).sort()
  const deprecated = list.licenses.filter((l) => l.isDeprecatedLicenseId).map((l) => l.licenseId).sort()
  const exceptionIds = exceptions.exceptions.map((e) => e.licenseExceptionId).sort()
  const quote = (values: string[]) => values.map((v) => `  ${JSON.stringify(v)},`).join('\n')
  mkdirSync(join(root, 'src/spdx'), { recursive: true })
  writeFileSync(
    join(root, 'src/spdx/list.generated.ts'),
    `// Generated by scripts/pin-legal-texts.ts from spdx/license-list-data ${SPDX_TAG}. Don't edit.\n\n` +
      `export const SPDX_LIST_VERSION = ${JSON.stringify(SPDX_VERSION)}\n\n` +
      `export const LICENSE_IDS: readonly string[] = [\n${quote(ids)}\n]\n\n` +
      `export const DEPRECATED_IDS: readonly string[] = [\n${quote(deprecated)}\n]\n\n` +
      `export const EXCEPTION_IDS: readonly string[] = [\n${quote(exceptionIds)}\n]\n`,
  )

  mkdirSync(legalDir, { recursive: true })
  for (const id of TEXT_IDS) {
    if (!ids.includes(id)) throw new Error(`${id} is not on the SPDX ${SPDX_VERSION} list`)
    const bytes = new Uint8Array(await (await get(`text/${id}.txt`)).arrayBuffer())
    writeFileSync(join(legalDir, `${id}.txt`), bytes)
  }
}

function hashAll(): void {
  const hashes: Record<string, string> = {}
  for (const file of readdirSync(legalDir).filter((f) => f.endsWith('.txt')).sort()) {
    hashes[file.slice(0, -'.txt'.length)] = bytesToHex(sha256(readFileSync(join(legalDir, file))))
  }
  writeFileSync(join(legalDir, 'hashes.generated.json'), JSON.stringify(hashes, null, 2) + '\n')
  for (const [id, hash] of Object.entries(hashes)) console.log(`${hash}  ${id}`)
}

if (!process.argv.includes('--hash-only')) await fetchAll()
hashAll()
