// Regenerates acceptAllPaymaster.ts from AcceptAllPaymaster.sol. Needs solc 0.8.25+ on PATH:
// bun test-utils/aaStack/compileAcceptAllPaymaster.ts (from packages/publish)
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = import.meta.dir
const out = spawnSync('solc', ['--bin', '--optimize', '--evm-version', 'cancun', join(dir, 'AcceptAllPaymaster.sol')], {
  encoding: 'utf8',
})
if (out.status !== 0) throw new Error(out.stderr)
const bin = out.stdout.split('Binary:')[1]?.trim().split(/\s/)[0]
if (!bin) throw new Error(`no bytecode in solc output:\n${out.stdout}`)
writeFileSync(
  join(dir, 'acceptAllPaymaster.ts'),
  `// Generated by compileAcceptAllPaymaster.ts from AcceptAllPaymaster.sol. Don't edit.\nexport const ACCEPT_ALL_PAYMASTER_BYTECODE = '0x${bin}' as const\n`,
)
